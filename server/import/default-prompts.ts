function preset(entries: [string, string][]): PromptPreset {
  return {
    id: '00000000-0000-4000-8000-000000000001',
    name: '标准纸箱订单识别',
    entries: entries.map(([name, content], i) => ({
      id: `00000000-0000-4000-8000-${String(i + 10).padStart(12, '0')}`,
      name,
      content,
      enabled: true,
    })),
  };
}

/** 仅用于安全识别“尚未被用户修改的旧默认预设”。 */
export function legacyDefaultPromptPreset(): PromptPreset {
  return preset(legacyRules);
}

// 仅业务识别规则可编辑；输出契约、安全边界及后端校验独立于这些条目。
export function defaultPromptPreset(): PromptPreset {
  return preset([...correctedRules, customerRule, unitRule]);
}
