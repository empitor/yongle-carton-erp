export const developerCommandSchema = z.strictObject({
  requestId: z.string().uuid(),
  module: z.enum(developerModules),
  action: z.enum([
    'create',
    'update',
    'archive',
    'restore',
    'permanent-delete',
    'delete',
    'confirm',
    'cancel',
    'reverse',
    'move',
  ]),
  items: z
    .array(
      z.strictObject({ id: z.number().int().positive(), version: z.number().int().positive() }),
    )
    .max(100)
    .default([]),
  patch: z.record(z.string(), z.unknown()).default({}),
  patches: z.record(z.string(), z.record(z.string(), z.unknown())).optional(),
  impactDigests: z.record(z.string(), z.string().regex(/^[a-f0-9]{64}$/)).optional(),
  deletionDigest: z.string().optional(),
  inventoryPolicy: z.enum(['preserve', 'recalculate']).optional(),
  reason: z.string().trim().min(1).max(1000),
});
